def create_fresh_atm():
    """
    Создание свежего экземпляра ATM с чистыми файлами данных
    Удаляет существующие файлы с картами и пользователями для чистоты эксперимента
    
    Возвращает:
        ATMCore: Новый экземпляр банкомата с пустыми данными
    """
    # Перебираем два файла, которые используются для хранения данных
    for file in ["atm_cards.json", "atm_users.json"]:
        if os.path.exists(file):  # Проверяем, существует ли файл
            os.remove(file)       # Удаляем его для чистой инициализации
    
    # Импортируем класс банкомата (после удаления файлов, чтобы создать новые)
    from atm_core import ATMCore
    return ATMCore()  # Возвращаем новый экземпляр с демо-данными


def print_table():
    """
    Вывод таблицы производительности WWW-БАНК
    Измеряет и отображает:
    1. Скорость выполнения различных операций
    2. Потребление памяти при нагрузке
    3. Итоговую оценку системы
    """
    
    # Заголовок таблицы
    print("\n" + "="*80)
    print("              ТАБЛИЦА ПРОИЗВОДИТЕЛЬНОСТИ WWW-БАНК")
    print("="*80)
    
    # Создаем свежий экземпляр банкомата для тестов
    atm = create_fresh_atm()
    
    # ========== ПОДГОТОВКА ТЕСТОВОЙ КАРТЫ ==========
    # Регистрируем новую тестовую карту
    success, msg, data = atm.register_new_card("1234", "Тест")
    if not success:
        print(f"Ошибка: {msg}")
        return
    
    card = data["number"]  # Получаем номер карты
    
    # Авторизуемся и пополняем баланс для возможности проведения операций
    atm.login(card, "1234")
    atm.deposit(100000)  # Кладем 100 000 ₽ на счет
    
    # ========== 1. ТЕСТЫ СКОРОСТИ ОПЕРАЦИЙ ==========
    print("\n 1. СКОРОСТЬ ОДИНОЧНЫХ ОПЕРАЦИЙ")
    print("-" * 80)
    print(f" {'Операция':<20} | {'Время (мс)':<12} | {'Оценка':<15}")
    print("-" * 80)
    
    # ----- Тест 1: Проверка баланса -----
    # Замеряем время выполнения 1000 проверок баланса
    start = time.perf_counter()  # Высокоточный таймер
    for _ in range(1000):
        atm.check_balance()
    # Вычисляем среднее время одной операции в миллисекундах
    balance_time = (time.perf_counter() - start) / 1000 * 1000
    
    # Оценка производительности: < 1 мс - отлично, иначе - нормально
    print(f" {'Проверка баланса':<20} | {balance_time:<12.2f} | {'Отлично' if balance_time < 1 else 'Нормально'}")
    
    # ----- Тест 2: Пополнение счета -----
    # 100 операций пополнения
    start = time.perf_counter()
    for _ in range(100):
        atm.deposit(100)
    deposit_time = (time.perf_counter() - start) / 100 * 1000
    print(f" {'Пополнение':<20} | {deposit_time:<12.2f} | {'Отлично' if deposit_time < 2 else 'Нормально'}")
    
    # ----- Тест 3: Снятие наличных -----
    # Выполняем 100 циклов "снятие + пополнение", чтобы баланс не уходил в минус
    start = time.perf_counter()
    for _ in range(100):
        atm.withdraw(50)    # Снимаем 50 ₽
        atm.deposit(50)     # Возвращаем обратно
    withdraw_time = (time.perf_counter() - start) / 100 * 1000
    print(f" {'Снятие':<20} | {withdraw_time:<12.2f} | {'Отлично' if withdraw_time < 2 else 'Нормально'}")
    
    # ----- Тест 4: Оплата мобильной связи -----
    # 50 операций оплаты
    start = time.perf_counter()
    for _ in range(50):
        atm.pay_mobile("9123456789", 100, "MTS")
    mobile_time = (time.perf_counter() - start) / 50 * 1000
    print(f" {'Оплата связи':<20} | {mobile_time:<12.2f} | {'Отлично' if mobile_time < 5 else 'Нормально'}")
    
    print("\n")
    
    # ========== 2. ТЕСТЫ ПОТРЕБЛЕНИЯ ПАМЯТИ ==========
    print(" 2. ПОТРЕБЛЕНИЕ ПАМЯТИ")
    print("-" * 80)
    
    # Создаем отдельный экземпляр для тестирования памяти
    # Это нужно, чтобы данные из предыдущих тестов не влияли на результат
    mem_atm = create_fresh_atm()
    
    # Начинаем отслеживание памяти
    tracemalloc.start()
    start_mem = tracemalloc.get_traced_memory()[0]  # Память до нагрузки
    
    # ----- Создаем нагрузку на систему -----
    test_users = []  # Список для хранения созданных пользователей
    
    # Регистрируем 30 тестовых пользователей
    for i in range(30):
        pin = f"mem{i:04d}"  # Генерируем PIN: mem0000, mem0001, ...
        success, msg, data = mem_atm.register_new_card(pin, f"MemUser{i}")
        if success and data:
            # Сохраняем пару (номер карты, PIN) для последующей авторизации
            test_users.append((data["number"], pin))
    
    # Для первых 10 пользователей выполняем по 10 операций
    for card, pin in test_users[:10]:
        mem_atm.login(card, pin)      # Вход в систему
        for _ in range(10):
            mem_atm.check_balance()   # Проверка баланса
            mem_atm.deposit(100)      # Пополнение
    
    # Получаем текущее и пиковое использование памяти
    current_mem, peak_mem = tracemalloc.get_traced_memory()
    tracemalloc.stop()  # Останавливаем отслеживание
    
    # Вычисляем использованную память (пик - начало)
    used_mb = (peak_mem - start_mem) / (1024 * 1024)
    
    # Вывод результатов в удобочитаемом формате
    print(f" {'Начальная память':<25} : {start_mem / 1024:>10.2f} KB")    # КБ
    print(f" {'Пиковое использование':<25} : {peak_mem / 1024:>10.2f} KB") # КБ
    print(f" {'Использовано всего':<25} : {used_mb:>10.2f} MB")           # МБ
    
    # Оценка использования памяти
    if used_mb < 10:
        mem_status = "Отлично"      # Менее 10 МБ - отличный результат
    elif used_mb < 50:
        mem_status = "Нормально"    # 10-50 МБ - приемлемо
    else:
        mem_status = "Много"        # Более 50 МБ - нужно оптимизировать
    print(f" {'Оценка':<25} : {mem_status}")
    
    print("\n")
    
    # ========== 3. ИТОГОВАЯ ОЦЕНКА СИСТЕМЫ ==========
    print(" 3. ИТОГОВАЯ ОЦЕНКА СИСТЕМЫ")
    print("-" * 80)
    
    # Рассчитываем среднюю скорость по основным операциям
    # (проверка баланса, пополнение, снятие)
    avg_speed = (balance_time + deposit_time + withdraw_time) / 3
    
    print(f" {'Средняя скорость операций':<30} : {avg_speed:.2f} мс")
    print(f" {'Потребление памяти':<30} : {used_mb:.2f} MB")
    print("-" * 80)
    
    # Финальный вердикт на основе показателей
    if avg_speed < 2 and used_mb < 20:
        # Скорость < 2 мс И память < 20 МБ
        print(" ИТОГ: СИСТЕМА РАБОТАЕТ СТАБИЛЬНО И БЫСТРО")
        print("        Рекомендуется к использованию")
    elif avg_speed < 5 and used_mb < 50:
        # Скорость < 5 мс И память < 50 МБ
        print(" ИТОГ: СИСТЕМА РАБОТАЕТ НОРМАЛЬНО")
        print("        Возможна оптимизация при росте нагрузки")
    else:
        # Низкая производительность или высокое потребление памяти
        print(" ИТОГ: ТРЕБУЕТСЯ ОПТИМИЗАЦИЯ")
        print("        Рекомендуется улучшить производительность")
    
    print("="*80)
    print()


